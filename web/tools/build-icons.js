import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(__dirname, "..", "assets", "gel", "icons");
const outFile = join(__dirname, "..", "icons.js");

const files = readdirSync(iconsDir).filter((f) => f.endsWith(".svg"));
const entries = files.map((f) => {
  const name = f.replace("-outlined.svg", "").replace(".svg", "");
  const svg = readFileSync(join(iconsDir, f), "utf8")
    .replace(/#0000FF/gi, "currentColor")
    .replace(/\s+/g, " ")
    .trim();
  return `  ${JSON.stringify(name)}: ${JSON.stringify(svg)}`;
});

const banner =
  "// Auto-generated by tools/build-icons.js from assets/gel/icons/*.svg (fill -> currentColor).\n" +
  "// Do not edit by hand — run `npm run build:icons` to regenerate.\n";
const out = banner + "window.GEL_ICONS = {\n" + entries.join(",\n") + "\n};\n";
writeFileSync(outFile, out, "utf8");
console.log(`Wrote web/icons.js with ${entries.length} icons`);
